#!/usr/bin/env node
/**
 * After CloudFormation deploy (infra/iot-core/template.yaml), creates two device certificates,
 * attaches IoT policies + Things, downloads Amazon Root CA, writes env snippets.
 *
 * Requires: AWS credentials (aws configure), stack already deployed (npm run iot:deploy).
 */

import {
  IoTClient,
  CreateKeysAndCertificateCommand,
  AttachPolicyCommand,
  AttachThingPrincipalCommand,
  DescribeEndpointCommand,
} from '@aws-sdk/client-iot';
import { CloudFormationClient, DescribeStacksCommand } from '@aws-sdk/client-cloudformation';
import fs from 'node:fs';
import path from 'node:path';
import https from 'node:https';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const region = process.env.AWS_REGION || process.env.AWS_DEFAULT_REGION || 'us-east-1';
const stackName = process.env.IOT_STACK_NAME || 'thermosentinel-iot';

const AMAZON_ROOT_CA_URL = 'https://www.amazontrust.com/repository/AmazonRootCA1.pem';

function httpsGet(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode !== 200) {
          reject(new Error(`HTTP ${res.statusCode}`));
          return;
        }
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
      })
      .on('error', reject);
  });
}

async function getStackOutputs() {
  const cf = new CloudFormationClient({ region });
  const res = await cf.send(new DescribeStacksCommand({ StackName: stackName }));
  const stack = res.Stacks?.[0];
  if (!stack) throw new Error(`Stack not found: ${stackName}`);
  const outs = stack.Outputs || [];
  const map = {};
  for (const o of outs) {
    if (o.OutputKey && o.OutputValue != null) map[o.OutputKey] = o.OutputValue;
  }
  return map;
}

async function ensureAmazonRootCa() {
  const dest = path.join(root, 'certs', 'AmazonRootCA1.pem');
  if (fs.existsSync(dest)) return dest;
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const pem = await httpsGet(AMAZON_ROOT_CA_URL);
  fs.writeFileSync(dest, pem, 'utf8');
  console.log('Wrote', dest);
  return dest;
}

async function provisionIdentity({ label, thingName, policyName, outDir }) {
  const iot = new IoTClient({ region });
  const cert = await iot.send(new CreateKeysAndCertificateCommand({ setAsActive: true }));
  const arn = cert.certificateArn;
  const privateKey = cert.keyPair?.PrivateKey ?? cert.keyPair?.privateKey;
  if (!arn || !cert.certificatePem || !privateKey) {
    throw new Error(`Missing cert fields from CreateKeysAndCertificate for ${label}`);
  }
  await iot.send(new AttachPolicyCommand({ policyName, target: arn }));
  await iot.send(new AttachThingPrincipalCommand({ thingName, principal: arn }));
  fs.mkdirSync(outDir, { recursive: true });
  const certPath = path.join(outDir, 'certificate.pem.crt');
  const keyPath = path.join(outDir, 'private.pem.key');
  fs.writeFileSync(certPath, cert.certificatePem, 'utf8');
  fs.writeFileSync(keyPath, privateKey, 'utf8');
  console.log(`[${label}] Thing=${thingName} policy=${policyName}`);
  console.log(`[${label}] cert=${certPath}`);
  return { certPath, keyPath, arn };
}

async function main() {
  console.log(`Region=${region} Stack=${stackName}`);
  const o = await getStackOutputs();
  const sensorThing = o.SensorThingName;
  const fogThing = o.FogThingName;
  const sensorPolicy = o.SensorPolicyName;
  const fogPolicy = o.FogPolicyName;
  const dataTopic = o.MqttDataTopic || `sensors/${sensorThing}/data`;
  if (!sensorThing || !fogThing || !sensorPolicy || !fogPolicy) {
    throw new Error(
      'Missing stack outputs. Deploy first: npm run iot:deploy\n' + JSON.stringify(o, null, 2),
    );
  }

  const caPath = await ensureAmazonRootCa();
  const iot = new IoTClient({ region });
  const ep = await iot.send(new DescribeEndpointCommand({ endpointType: 'iot:Data-ATS' }));
  const host = ep.endpointAddress;
  if (!host) throw new Error('Could not resolve IoT data endpoint');
  const mqttUrl = `mqtts://${host}:8883`;

  const sensorDir = path.join(root, 'certs', 'sensor');
  const fogDir = path.join(root, 'certs', 'fog');

  await provisionIdentity({
    label: 'sensor',
    thingName: sensorThing,
    policyName: sensorPolicy,
    outDir: sensorDir,
  });
  await provisionIdentity({
    label: 'fog',
    thingName: fogThing,
    policyName: fogPolicy,
    outDir: fogDir,
  });

  const envPath = path.join(root, '.env.iot.generated');
  const body = `# Generated by npm run iot:provision — do not commit certs/ or this file with secrets
# IoT Core data endpoint (ATS)
MQTT_BROKER_URL=${mqttUrl}
AWS_IOT_CA_PATH=certs/AmazonRootCA1.pem

# --- Terminal A: sensor simulator (use these together) ---
# SIMULATOR_MQTT_CLIENT_ID=${sensorThing}
# MQTT_TOPIC_MODE=iot
# MQTT_DATA_TOPIC=${dataTopic}
# AWS_IOT_CERT_PATH=certs/sensor/certificate.pem.crt
# AWS_IOT_KEY_PATH=certs/sensor/private.pem.key

# --- Terminal B: fog node (different cert than sensor) ---
# FOG_MQTT_CLIENT_ID=${fogThing}
# MQTT_TOPIC_FILTER=sensors/#
# AWS_IOT_CERT_PATH=certs/fog/certificate.pem.crt
# AWS_IOT_KEY_PATH=certs/fog/private.pem.key
`;
  fs.writeFileSync(envPath, body, 'utf8');
  console.log('\nWrote', envPath);
  console.log('\nNext: open two terminals and paste the commented blocks from .env.iot.generated (uncomment), or merge into .env.local');
  console.log('Broker URL:', mqttUrl);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
